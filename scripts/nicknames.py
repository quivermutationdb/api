#!/usr/bin/env python3
"""
scripts/nicknames.py — curated class nicknames (data/nicknames.json).

    python scripts/nicknames.py --check [--golden tests/golden/ids-n4.json]
        Validate the file: id/slug format, uniqueness, and that each entry's
        member `matrix` really belongs to its `mc_id` (quiver_id(matrix) must be
        a member of that class in the reference dataset). CI runs this.

    python scripts/nicknames.py --sql dist/nicknames.sql
        Render an idempotent full replacement of the class_nicknames table:
            wrangler d1 execute qmd --remote --file=dist/nicknames.sql

    python scripts/nicknames.py --resolve
        After a re-keying, recompute each entry's mc_id from its matrix
        (explores the class; slow for big classes) and rewrite the file.

The JSON in git is the source of truth; the table is derived. Adding a name
means editing the file and merging to main — that is the access control.
"""
import argparse
import json
import os
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))

ROOT = os.path.join(os.path.dirname(__file__), "..")
DATA = os.path.join(ROOT, "data", "nicknames.json")
DEFAULT_GOLDEN = os.path.join(ROOT, "tests", "golden", "ids-n4.json")

MC_RE = re.compile(r"^MC\.n(\d+)\.[0-9a-f]{16}$")
SLUG_RE = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")


def load():
    with open(DATA, encoding="utf-8") as f:
        return json.load(f)


def check(golden_path: str) -> int:
    from qmd.core import quiver_id, to_matrix, is_skew_symmetric

    doc = load()
    entries = doc.get("nicknames", [])
    membership = {}
    if os.path.exists(golden_path):
        with open(golden_path, encoding="utf-8") as f:
            membership = json.load(f).get("membership", {})
    problems = []
    seen_ids, seen_slugs = set(), set()
    for i, e in enumerate(entries):
        where = f"entry {i} ({e.get('mc_id')!r})"
        for key in ("mc_id", "nickname", "slug", "matrix"):
            if key not in e:
                problems.append(f"{where}: missing {key!r}")
        if problems and problems[-1].startswith(where):
            continue
        if not MC_RE.match(e["mc_id"]):
            problems.append(f"{where}: bad mc_id format")
        if not SLUG_RE.match(e["slug"]):
            problems.append(f"{where}: slug must be lowercase [a-z0-9-]")
        if e["mc_id"] in seen_ids:
            problems.append(f"{where}: duplicate mc_id")
        if e["slug"] in seen_slugs:
            problems.append(f"{where}: duplicate slug {e['slug']!r}")
        seen_ids.add(e["mc_id"]); seen_slugs.add(e["slug"])
        try:
            m = to_matrix(e["matrix"])
            if not is_skew_symmetric(m):
                problems.append(f"{where}: matrix is not skew-symmetric")
            elif f"MC.n{len(m)}." not in e["mc_id"]:
                problems.append(f"{where}: matrix rank {len(m)} does not match mc_id rank")
            else:
                qid = quiver_id(m)
                known = membership.get(qid)
                if known is None:
                    print(f"  note: {where}: {qid} not in {os.path.basename(golden_path)}; "
                          "membership not verified")
                elif known != e["mc_id"]:
                    problems.append(f"{where}: matrix belongs to {known}, not {e['mc_id']} "
                                    "— run --resolve if ids were re-keyed")
        except Exception as exc:  # noqa: BLE001
            problems.append(f"{where}: bad matrix ({exc})")
    for p in problems:
        print("  ERROR:", p)
    print(f"{len(entries)} nickname(s), {len(problems)} problem(s)")
    return 1 if problems else 0


def _lit(v) -> str:
    if v is None:
        return "NULL"
    return "'" + str(v).replace("'", "''") + "'"


def render_sql() -> str:
    entries = load().get("nicknames", [])
    lines = [
        "-- Quiver Mutation Database — curated class nicknames.",
        "-- Generated by: python scripts/nicknames.py --sql <file>  (from data/nicknames.json)",
        "-- Idempotent: replaces the whole class_nicknames table; never touched by rank imports.",
        "DELETE FROM class_nicknames;",
    ]
    for e in sorted(entries, key=lambda e: e["mc_id"]):
        lines.append(
            "INSERT INTO class_nicknames (mc_id, nickname, slug, note, added_by, added_at) VALUES ("
            + ", ".join(_lit(e.get(k)) for k in ("mc_id", "nickname", "slug", "note", "added_by", "added_at"))
            + ");"
        )
    return "\n".join(lines) + "\n"


def resolve() -> None:
    from qmd.core import explore_mutation_class, to_matrix

    doc = load()
    changed = 0
    for e in doc["nicknames"]:
        res = explore_mutation_class(to_matrix(e["matrix"]))
        if res.mc_id != e["mc_id"]:
            print(f"  {e['slug']}: {e['mc_id']} -> {res.mc_id}")
            e["mc_id"] = res.mc_id
            changed += 1
    with open(DATA, "w", encoding="utf-8") as f:
        json.dump(doc, f, indent=2, ensure_ascii=False)
        f.write("\n")
    print(f"resolved; {changed} id(s) changed")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--golden", default=DEFAULT_GOLDEN)
    ap.add_argument("--sql", metavar="FILE")
    ap.add_argument("--resolve", action="store_true")
    args = ap.parse_args()
    if args.check:
        sys.exit(check(args.golden))
    if args.sql:
        os.makedirs(os.path.dirname(os.path.abspath(args.sql)), exist_ok=True)
        with open(args.sql, "w", encoding="utf-8") as f:
            f.write(render_sql())
        print(f"wrote {args.sql}")
        return
    if args.resolve:
        resolve()
        return
    ap.print_help()


if __name__ == "__main__":
    main()
