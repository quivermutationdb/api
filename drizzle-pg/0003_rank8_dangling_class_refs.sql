-- Rank 8: drop 1,749 dangling mutation_class_id references.  (2026-09-09)
--
-- 1,749 of the 258,033 rank-8 quivers (0.68%) carry a mutation_class_id naming
-- a mutation_classes row that was never written. 1,740 distinct class ids, all
-- of them mutation-INFINITE members, all in-cell (max_edge = 1), all with
-- labeling_count NULL.
--
-- This is a defect in the GENERATED DATA, not in the load: the same 1,749 are
-- present in the source SQLite and in dist/d1's rank-8 parts, where a sampled
-- id (MC.n8.000d1755ebbc3f9c) appears exactly once -- as a quiver's class
-- reference, never as a class row. The mechanism is not established: rank 8 was
-- generated by an earlier state of qmd/d1_export.py, so reading today's
-- exporter does not reliably explain it, and no filter drops class rows at
-- render time (rank_stats.class_count reconciles with what was written).
--
-- Left alone the effect is user-visible and wrong: those quivers report
-- explored = true and link to a class page that 404s.
--
-- We NULL the reference rather than invent a class row. mutation_class_id NULL
-- is already the census's representation of "not explored" (CLAUDE.md), so this
-- lands the rows in an existing, honest state instead of a new one.
--
-- mutation_finite is deliberately NOT touched. It is a separate column with its
-- own provenance: these quivers were marked infinite by a real exploration that
-- crossed the weight bound, and that verdict is sound whether or not the class
-- row survived. Blanking it would discard a correct answer to tidy up a
-- different column. (Note Derksen-Owen does NOT cover them -- max_edge = 1.)
--
-- Idempotent, and a no-op on a dataset without the defect. Run AFTER the rank-8
-- data and BEFORE serving. The exporter-side fix is still open; regenerating
-- rank 8 should make this file a no-op, which is the test that it is fixed.

UPDATE quivers q
   SET mutation_class_id = NULL
 WHERE q.mutation_class_id IS NOT NULL
   AND NOT EXISTS (SELECT 1 FROM mutation_classes m WHERE m.id = q.mutation_class_id);
